// Embed the sample PDFs as base64 in a TS module so the serverless function
// can extract them without touching the filesystem (public/ is not readable
// from the lambda on Vercel).
import { readFileSync, writeFileSync } from "node:fs";
import { SAMPLES } from "../src/lib/samples.ts";

const entries = SAMPLES.map((s) => {
  const bytes = readFileSync(`public/contracts/${s.id}.pdf`);
  return `  "${s.id}": "${bytes.toString("base64")}",`;
});

writeFileSync(
  "src/data/samples/pdfs.ts",
  `// AUTO-GENERATED by scripts/export-pdfs.mjs — do not edit by hand.\n` +
    `// Serverless-safe copies of the sample contracts (base64).\n` +
    `export const SAMPLE_PDF_BASE64: Record<string, string> = {\n${entries.join("\n")}\n};\n`,
);
console.log("wrote src/data/samples/pdfs.ts");
